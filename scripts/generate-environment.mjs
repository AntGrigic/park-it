// Writes src/environments/environment.ts (git-ignored) so the Firebase config never lives in the repo.
// Values come from FIREBASE_* environment variables (CI secrets) or, locally, from .env.local.
// With no values the app runs in demo mode; pass --require-firebase to fail instead (used by the deploy).
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const envFilePath = resolve(projectRoot, '.env.local');
const outputPath = resolve(projectRoot, 'src/environments/environment.ts');

const variableNames = {
  apiKey: 'FIREBASE_API_KEY',
  authDomain: 'FIREBASE_AUTH_DOMAIN',
  projectId: 'FIREBASE_PROJECT_ID',
  storageBucket: 'FIREBASE_STORAGE_BUCKET',
  messagingSenderId: 'FIREBASE_MESSAGING_SENDER_ID',
  appId: 'FIREBASE_APP_ID',
};

function readEnvFile(filePath) {
  if (!existsSync(filePath)) {
    return {};
  }
  const values = {};
  for (const line of readFileSync(filePath, 'utf8').split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (match) {
      const [, name, rawValue] = match;
      values[name] = rawValue.replace(/^(['"])(.*)\1$/, '$2');
    }
  }
  return values;
}

const fileValues = readEnvFile(envFilePath);
const firebase = Object.fromEntries(
  Object.entries(variableNames).map(([option, variable]) => [
    option,
    process.env[variable] || fileValues[variable] || '',
  ]),
);
const missingVariables = Object.entries(variableNames)
  .filter(([option]) => !firebase[option])
  .map(([, variable]) => variable);

if (missingVariables.length > 0 && process.argv.includes('--require-firebase')) {
  console.error(
    `Missing Firebase config: ${missingVariables.join(', ')}.\n` +
      'Add them under GitHub → Settings → Secrets and variables → Actions → Repository secrets.',
  );
  process.exit(1);
}

const configLines = Object.entries(firebase)
  .map(([option, value]) => `    ${option}: ${JSON.stringify(value)},`)
  .join('\n');

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(
  outputPath,
  `// Generated by scripts/generate-environment.mjs — do not edit or commit.
// Local values live in .env.local; the deploy reads FIREBASE_* repository secrets.
export const environment = {
  firebase: {
${configLines}
  },
};
`,
);

if (missingVariables.length === Object.keys(variableNames).length) {
  console.log('environment.ts: no Firebase config found — the app runs in demo mode.');
} else if (missingVariables.length > 0) {
  console.warn(`environment.ts: Firebase config is incomplete (missing ${missingVariables.join(', ')}).`);
} else {
  console.log('environment.ts: Firebase config written.');
}
